pub fn to_cp437(c: char) -> FontCharType {
    if (' '..='~').contains(&c) {
        return c as FontCharType;
    }
    CP437.iter().position(|&x| x == c).unwrap_or(0) as FontCharType
}

pub fn cp437_to_char(glyph: FontCharType) -> char {
    CP437.get(glyph as usize).copied().unwrap_or('\0')
}

#[cfg(test)]
mod tests {
    use super::*;
 
    #[test]
    fn round_trips_every_code() {
        for code in 1..256u16 {
            assert_eq!(to_cp437(cp437_to_char(code)), code, "code {code}");
        }
        assert_eq!(to_cp437('@'), 64);
        assert_eq!(to_cp437('▒'), 177);
        assert_eq!(to_cp437('♣'), 5);
        assert_eq!(to_cp437('火'), 0);
    }
}